/*
 * config.h - the only file you should need to edit.
 *
 * Shared by macropad.exe and macropad_hook.dll, so both always agree on
 * which keys are "pad keys".
 */
#ifndef MACROPAD_CONFIG_H
#define MACROPAD_CONFIG_H

#include <windows.h>

/*
 * Substring matched (case-insensitively) against each keyboard's device
 * path, e.g.
 *   \\?\HID#VID_514C&PID_8851&MI_01&COL01#8&3cba26a&0&0000#{884b96c3-...}
 *
 * Only the vendor/product IDs are used. They are burned into the pad's
 * firmware, so they're the same on every PC and every USB port. The rest of
 * the path (the "8&3cba26a&0&0000" instance part) is generated by Windows and
 * changes between machines/ports, which is why the old Lua script broke when
 * you moved PCs. Run `macropad.exe --list` to see what your pad reports.
 */
#define MACROPAD_DEVICE_ID L"VID_514C&PID_8851"

/* What each pad key turns into. `from` is the virtual-key code the pad sends,
 * `to` is the virtual-key code we inject instead. */
typedef struct {
    BYTE from;
    BYTE to;
} KeyMapping;

static const KeyMapping KEY_MAP[] = {
    { 'A', VK_MEDIA_PREV_TRACK },  /* key 1        */
    { 'B', VK_MEDIA_PLAY_PAUSE },  /* key 2        */
    { 'C', VK_MEDIA_NEXT_TRACK },  /* key 3        */
    { '1', VK_VOLUME_DOWN      },  /* knob CCW     */
    { '2', VK_VOLUME_MUTE      },  /* knob press   */
    { '3', VK_VOLUME_UP        },  /* knob CW      */
};

#define KEY_MAP_COUNT (sizeof KEY_MAP / sizeof KEY_MAP[0])

/* Returns the replacement VK for a pad key, or 0 if the key isn't mapped. */
static __inline BYTE map_key(UINT vk)
{
    for (UINT i = 0; i < KEY_MAP_COUNT; i++)
        if (KEY_MAP[i].from == vk)
            return KEY_MAP[i].to;
    return 0;
}

#endif
